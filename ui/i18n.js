const COUNTS_IT = {"tracks":["{n} brano", "{n} brani"], "unplayed":["{n} non riprodotto", "{n} non riprodotti"]};

/** The text in the screen's language, with `{name}` placeholders filled from `vars`. */
const TABLES = { cs: CS, sk: SK, hu: HU, de: DE, fr: FR, es: ES, it: IT };

function t(text, vars) {
  let out = (TABLES[LANG] && TABLES[LANG][text]) || text;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

// Counted words: English one/other; Czech and Slovak one (1), few (2–4) and many (0, 5+);
// Hungarian one form (a noun stays singular after a number); German, Spanish and Italian
// one (1) and other; French one (0 and 1) and other.
const COUNTS = {
  tracks: { en: ['{n} track', '{n} tracks'], cs: ['{n} skladba', '{n} skladby', '{n} skladeb'], sk: COUNTS_SK.tracks, hu: COUNTS_HU.tracks, de: COUNTS_DE.tracks, fr: COUNTS_FR.tracks, es: COUNTS_ES.tracks, it: COUNTS_IT.tracks },
  unplayed: { en: ['{n} unplayed', '{n} unplayed'], cs: ['{n} nepřehraná', '{n} nepřehrané', '{n} nepřehraných'], sk: COUNTS_SK.unplayed, hu: COUNTS_HU.unplayed, de: COUNTS_DE.unplayed, fr: COUNTS_FR.unplayed, es: COUNTS_ES.unplayed, it: COUNTS_IT.unplayed },
};

function tn(n, key) {
  const f = COUNTS[key][LANG] || COUNTS[key].en;
  let form;
  if (LANG === 'cs' || LANG === 'sk') form = n === 1 ? f[0] : n >= 2 && n <= 4 ? f[1] : f[2];
  else if (LANG === 'hu') form = f[0];
  else if (LANG === 'fr') form = n <= 1 ? f[0] : f[1];
  else form = n === 1 ? f[0] : f[1];
  return form.replace('{n}', n);
}

/** The locale for dates. */
function locale() {
  return { cs: 'cs-CZ', sk: 'sk-SK', hu: 'hu-HU', de: 'de-DE', fr: 'fr-FR', es: 'es-ES', it: 'it-IT' }[LANG] || 'en-GB';
}

/** Static texts in the page carry `data-i18n` with their English text. */
function translatePage() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach((node) => { node.textContent = t(node.dataset.i18n); });
}
